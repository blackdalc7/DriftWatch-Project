"""Export validation results as a MITRE ATT&CK Navigator layer.

Each technique is coloured by its best recent outcome across the fleet: prevented (green), detected
(blue), missed (red), error (grey). The score is the share of (test, agent) results for that technique
that passed, so a technique that is detected on one host and missed on another shows up as 50 with both
results in its comment. Techniques with tests that have never run are listed with no colour and the
comment "not yet run", so coverage gaps in the library are visible too.
"""

from __future__ import annotations

from collections import defaultdict
from typing import Any

from driftwatch.schema import DriftwatchTest

COLORS = {"prevented": "#2ea043", "detected": "#1f6feb", "missed": "#da3633", "error": "#8b949e"}
RANK = {"prevented": 3, "detected": 2, "missed": 1, "error": 0}
NAVIGATOR_VERSION = "5.1.0"
LAYER_VERSION = "4.5"
ATTACK_VERSION = "17"


def build_layer(tests: list[DriftwatchTest], results: list[dict[str, Any]], agents: dict[str, dict[str, Any]],
                name: str = "Driftwatch validation coverage") -> dict[str, Any]:
    """Build the layer JSON from the library and the latest evaluated run per (test, agent)."""
    by_test = {t.id: t for t in tests}
    per_technique: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for run in results:
        test = by_test.get(run["test_id"])
        if test is None or not run.get("outcome"):
            continue
        for technique in test.attack.techniques:
            per_technique[technique].append(run)
    planned = {t for test in tests for t in test.attack.techniques}
    techniques = []
    for technique in sorted(planned | set(per_technique)):
        runs = per_technique.get(technique, [])
        if not runs:
            techniques.append({"techniqueID": technique, "comment": "not yet run", "enabled": True,
                               "metadata": [{"name": "tests", "value": ", ".join(
                                   sorted(t.id for t in tests if technique in t.attack.techniques))}]})
            continue
        best = max(runs, key=lambda r: RANK.get(r["outcome"], -1))["outcome"]
        passed = sum(1 for r in runs if r.get("passed"))
        lines = []
        for r in sorted(runs, key=lambda r: (r["test_id"], r["agent_id"])):
            host = agents.get(r["agent_id"], {}).get("hostname", r["agent_id"])
            lines.append(f"{r['test_id']} on {host}: {r['outcome']}{' (pass)' if r.get('passed') else ' (fail)'}")
        techniques.append({
            "techniqueID": technique,
            "score": round(100 * passed / len(runs)),
            "color": COLORS.get(best, COLORS["error"]),
            "comment": "\n".join(lines),
            "enabled": True,
            "metadata": [{"name": "best outcome", "value": best},
                         {"name": "results", "value": str(len(runs))}],
        })
    return {
        "name": name,
        "versions": {"attack": ATTACK_VERSION, "navigator": NAVIGATOR_VERSION, "layer": LAYER_VERSION},
        "domain": "enterprise-attack",
        "description": "Generated by Driftwatch from the latest evaluated run of each test on each agent.",
        "sorting": 3,
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#da3633", "#d29922", "#2ea043"], "minValue": 0, "maxValue": 100},
        "legendItems": [{"label": k, "color": v} for k, v in COLORS.items()],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#161b22",
    }
