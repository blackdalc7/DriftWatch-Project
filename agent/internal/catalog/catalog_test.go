package catalog

import (
	"encoding/json"
	"os"
	"sort"
	"testing"
)

type pyParam struct {
	Name     string   `json:"name"`
	Kind     string   `json:"kind"`
	Required bool     `json:"required"`
	Choices  []string `json:"choices"`
	Minimum  *int     `json:"minimum"`
	Maximum  *int     `json:"maximum"`
}

type pyAction struct {
	ID             string            `json:"id"`
	Platforms      []string          `json:"platforms"`
	Params         []pyParam         `json:"params"`
	ChoicePlatform map[string]string `json:"choice_platform"`
}

// TestCatalogMatchesPython fails when the Go catalog and src/driftwatch/catalog.py drift apart.
// testdata/catalog.json is regenerated by `driftwatch catalog` in CI before this test runs.
func TestCatalogMatchesPython(t *testing.T) {
	data, err := os.ReadFile("testdata/catalog.json")
	if err != nil {
		t.Fatal(err)
	}
	var py []pyAction
	if err := json.Unmarshal(data, &py); err != nil {
		t.Fatal(err)
	}
	if len(py) != len(Actions) {
		t.Fatalf("python catalog has %d actions, go has %d", len(py), len(Actions))
	}
	for _, pa := range py {
		ga, ok := Actions[pa.ID]
		if !ok {
			t.Fatalf("action %s missing from the Go catalog", pa.ID)
		}
		if !equalSet(pa.Platforms, ga.Platforms) {
			t.Errorf("%s platforms differ: %v vs %v", pa.ID, pa.Platforms, ga.Platforms)
		}
		if len(pa.Params) != len(ga.Params) {
			t.Fatalf("%s params differ", pa.ID)
		}
		for i, pp := range pa.Params {
			gp := ga.Params[i]
			if pp.Name != gp.Name || pp.Kind != gp.Kind || pp.Required != gp.Required || !equalSet(pp.Choices, gp.Choices) {
				t.Errorf("%s param %s differs", pa.ID, pp.Name)
			}
			if pp.Minimum != nil && (*pp.Minimum != gp.Min || *pp.Maximum != gp.Max) {
				t.Errorf("%s param %s range differs", pa.ID, pp.Name)
			}
		}
		for choice, plat := range pa.ChoicePlatform {
			if ga.ChoicePlatform[choice] != plat {
				t.Errorf("%s choice %s platform differs", pa.ID, choice)
			}
		}
	}
}

func equalSet(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	x, y := append([]string{}, a...), append([]string{}, b...)
	sort.Strings(x)
	sort.Strings(y)
	for i := range x {
		if x[i] != y[i] {
			return false
		}
	}
	return true
}

func raw(m map[string]string) map[string]json.RawMessage {
	out := map[string]json.RawMessage{}
	for k, v := range m {
		out[k] = json.RawMessage(v)
	}
	return out
}

func TestValidate(t *testing.T) {
	cases := []struct {
		action, platform string
		params           map[string]string
		ok               bool
	}{
		{"process.discovery", Linux, map[string]string{"command": `"id"`}, true},
		{"process.discovery", Windows, map[string]string{"command": `"id"`}, false},
		{"process.discovery", Linux, map[string]string{"command": `"rm -rf /"`}, false},
		{"process.discovery", Linux, map[string]string{}, false},
		{"process.discovery", Linux, map[string]string{"command": `"id"`, "extra": `1`}, false},
		{"shell.exec", Linux, map[string]string{"cmd": `"id"`}, false},
		{"registry.run_key_canary", Linux, nil, false},
		{"file.eicar_drop", Linux, map[string]string{"wait_seconds": `61`}, false},
		{"file.eicar_drop", Linux, map[string]string{"wait_seconds": `1.5`}, false},
		{"file.eicar_drop", Linux, map[string]string{"wait_seconds": `"5"`}, false},
		{"file.eicar_drop", Linux, map[string]string{"wait_seconds": `5`}, true},
		{"dns.sinkhole_query", Windows, nil, true},
	}
	for _, c := range cases {
		_, err := Validate(c.action, raw(c.params), c.platform)
		if (err == nil) != c.ok {
			t.Errorf("%s %v on %s: err=%v, want ok=%v", c.action, c.params, c.platform, err, c.ok)
		}
	}
	p, _ := Validate("file.eicar_drop", nil, Linux)
	if p["wait_seconds"] != 10 {
		t.Errorf("default not applied: %v", p)
	}
}
